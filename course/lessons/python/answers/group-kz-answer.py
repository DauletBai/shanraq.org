"""28-сабақтың тапсырмасының шешімі: айлар мен санаттар бойынша есеп.

Екі кілт бойынша бір groupby, өз баған аттары, transform арқылы ай ішіндегі
үлес — және есепті оқуға жарамды ететін сұрыптау.
"""

import pandas as pd

rows = [
    ("2026-01-03", "Қостанай", "тамақ", 4200),
    ("2026-01-05", "Қостанай", "жанармай", 18500),
    ("2026-01-07", "Рудный", "тамақ", 2600),
    ("2026-01-09", "Қостанай", "байланыс", 4990),
    ("2026-01-15", "Қостанай", "жалдау", 95000),
    ("2026-01-18", "Рудный", "жанармай", 16200),
    ("2026-01-24", "Қостанай", "тамақ", 3100),
    ("2026-02-02", "Рудный", "тамақ", 2800),
    ("2026-02-06", "Қостанай", "жанармай", 19100),
    ("2026-02-11", "Қостанай", "байланыс", 4990),
    ("2026-02-15", "Қостанай", "жалдау", 95000),
    ("2026-02-20", "Рудный", "жалдау", 62000),
]
df = pd.DataFrame(rows, columns=["day", "city", "kind", "amount"])
df["day"] = pd.to_datetime(df["day"])
df["ай"] = df["day"].dt.to_period("M")

report = df.groupby(["ай", "kind"]).agg(
    түбіртек=("amount", "count"),
    барлығы=("amount", "sum"),
).reset_index()

# Үлес бүкіл кезеңнен емес, өз айынан есептеледі.
report["үлесі"] = (report["барлығы"] / report.groupby("ай")["барлығы"].transform("sum") * 100).round(1)
report = report.sort_values(["ай", "барлығы"], ascending=[True, False])

print(report.to_string(index=False))

print()
totals = df.groupby("ай")["amount"].sum()
print("айлар бойынша қорытынды:", {str(k): int(v) for k, v in totals.items()})
print("шығыс ең көп ай:", totals.idxmax())
