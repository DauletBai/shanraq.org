"""Задание урока 40: деньги по годам и проверка по второму источнику."""

import pandas as pd

# Нацбанк, конец года, млн тенге: наличные, M3 и денежная база.
NBK = pd.DataFrame(
    [
        (2019, 2_300_505, 21_322_070, 6_893_176),
        (2020, 2_828_046, 24_917_785, 9_777_551),
        (2021, 2_997_723, 30_099_291, 10_957_714),
        (2022, 3_360_653, 34_295_955, 11_874_422),
        (2023, 3_639_662, 38_301_572, 11_539_973),
        (2024, 4_374_546, 45_660_003, 14_606_537),
        (2025, 4_749_199, 52_751_740, 15_678_721),
    ],
    columns=["год", "M0", "M3", "база"],
).set_index("год")

# Всемирный банк: ВВП и широкая денежная масса в тенге, индекс цен 2010 = 100.
VVP = pd.Series({2019: 69_532_626.5, 2020: 70_649_033.2, 2021: 83_951_587.9,
                 2022: 103_765_518.2, 2023: 119_442_289.7, 2024: 136_693_318.3,
                 2025: 159_561_346.6})
BANK_M3 = pd.Series({2019: 21_322_070.31, 2020: 24_917_784.65, 2021: 30_099_290.60,
                     2022: 34_295_954.60, 2023: 38_301_571.83, 2024: 45_660_003.09,
                     2025: 52_751_740.08})
BAGA = pd.Series({2019: 189.30, 2020: 202.02, 2021: 218.27, 2022: 251.07,
                  2023: 287.54, 2024: 312.53, 2025: 348.12})


def count(nbk, vvp):
    """Доля наличных, деньги на тенге ВВП и денежный множитель по годам."""
    out = pd.DataFrame(index=nbk.index)
    out["M3"] = nbk["M3"]
    out["наличные"] = (nbk["M0"] / nbk["M3"] * 100).round(1)
    out["на тенге ВВП"] = (nbk["M3"] / vvp).round(3)
    out["множитель"] = (nbk["M3"] / nbk["база"]).round(3)
    return out


table = count(NBK, VVP)
print("== Деньги по годам")
print(table.to_string())

first, last = NBK.index[0], NBK.index[-1]
print()
print(f"== Что выросло за {first}–{last}, раз")
growth = pd.Series({
    "цены": BAGA[last] / BAGA[first],
    "ВВП": VVP[last] / VVP[first],
    "деньги M3": NBK.loc[last, "M3"] / NBK.loc[first, "M3"],
}).round(3)
print(growth.to_string())
print("  быстрее всех:", growth.idxmax())

print()
print("== Проверка по второму источнику")
diff = (BANK_M3.round() - NBK["M3"]).abs()
print("  наибольшее расхождение, млн тенге:", int(diff.max()))
print("  сходится во всех годах:", bool((diff == 0).all()))
