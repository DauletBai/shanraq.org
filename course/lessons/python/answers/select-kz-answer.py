"""27-сабақтың тапсырмасының шешімі: бір түбіртек кестесіне үш сұрақ.

Бір қаланың қымбат түбіртектері, loc арқылы қойылған «ірі» белгісі және тек ірі
түбіртектер бойынша қалалардың сомасы — бұлардың бәрі цикл емес, таңдау.
"""

import pandas as pd

rows = [
    ("2026-01-03", "Қостанай", "тамақ", 4200),
    ("2026-01-05", "Қостанай", "жанармай", 18500),
    ("2026-01-07", "Рудный", "тамақ", 2600),
    ("2026-01-09", "Қостанай", "байланыс", 4990),
    ("2026-01-12", "Астана", "тамақ", 7300),
    ("2026-01-15", "Қостанай", "жалдау", 95000),
    ("2026-01-18", "Рудный", "жанармай", 16200),
    ("2026-01-21", "Астана", "байланыс", 4990),
    ("2026-01-24", "Қостанай", "тамақ", 3100),
    ("2026-01-27", "Рудный", "жалдау", 62000),
]
df = pd.DataFrame(rows, columns=["day", "city", "kind", "amount"])
df["day"] = pd.to_datetime(df["day"])

print("Қостанайда 5000-нан қымбат:")
mask = (df["city"] == "Қостанай") & (df["amount"] > 5000)
print(df.loc[mask, ["day", "amount"]].to_string(index=False))

print()
print("түбіртектің мөлшері:")
df["мөлшері"] = "кәдімгі"
df.loc[df["amount"] >= 20000, "мөлшері"] = "ірі"
print(df["мөлшері"].value_counts().to_string())

print()
print("қалалар бойынша ірілері:")
big = df.loc[df["мөлшері"] == "ірі", ["city", "amount"]]
print(big.groupby("city")["amount"].sum().to_string())
