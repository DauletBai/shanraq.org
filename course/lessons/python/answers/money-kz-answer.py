"""40-сабақтың тапсырмасы: жылдар бойынша ақша және екінші дереккөзбен тексеру."""

import pandas as pd

# Ұлттық Банк, жыл соңы, млн теңге: қолма-қол, M3 және ақша базасы.
UB = pd.DataFrame(
    [
        (2019, 2_300_505, 21_322_070, 6_893_176),
        (2020, 2_828_046, 24_917_785, 9_777_551),
        (2021, 2_997_723, 30_099_291, 10_957_714),
        (2022, 3_360_653, 34_295_955, 11_874_422),
        (2023, 3_639_662, 38_301_572, 11_539_973),
        (2024, 4_374_546, 45_660_003, 14_606_537),
        (2025, 4_749_199, 52_751_740, 15_678_721),
    ],
    columns=["жыл", "M0", "M3", "база"],
).set_index("жыл")

# Дүниежүзілік банк: ЖІӨ мен кең ақша массасы теңгемен, баға индексі 2010 = 100.
JIO = pd.Series({2019: 69_532_626.5, 2020: 70_649_033.2, 2021: 83_951_587.9,
                 2022: 103_765_518.2, 2023: 119_442_289.7, 2024: 136_693_318.3,
                 2025: 159_561_346.6})
BANK_M3 = pd.Series({2019: 21_322_070.31, 2020: 24_917_784.65, 2021: 30_099_290.60,
                     2022: 34_295_954.60, 2023: 38_301_571.83, 2024: 45_660_003.09,
                     2025: 52_751_740.08})
BAGA = pd.Series({2019: 189.30, 2020: 202.02, 2021: 218.27, 2022: 251.07,
                  2023: 287.54, 2024: 312.53, 2025: 348.12})


def esepte(ub, jio):
    """Жылдар бойынша: қолма-қол үлесі, ЖІӨ теңгесіне ақша және көбейткіш."""
    out = pd.DataFrame(index=ub.index)
    out["M3"] = ub["M3"]
    out["қолма-қол"] = (ub["M0"] / ub["M3"] * 100).round(1)
    out["ЖІӨ теңгесіне"] = (ub["M3"] / jio).round(3)
    out["көбейткіш"] = (ub["M3"] / ub["база"]).round(3)
    return out


table = esepte(UB, JIO)
print("== Жылдар бойынша ақша")
print(table.to_string())

first, last = UB.index[0], UB.index[-1]
print()
print(f"== {first}–{last} жылдары не өсті, есе")
growth = pd.Series({
    "баға": BAGA[last] / BAGA[first],
    "ЖІӨ": JIO[last] / JIO[first],
    "ақша M3": UB.loc[last, "M3"] / UB.loc[first, "M3"],
}).round(3)
print(growth.to_string())
print("  ең жылдамы:", growth.idxmax())

print()
print("== Екінші дереккөзбен тексеру")
diff = (BANK_M3.round() - UB["M3"]).abs()
print("  ең үлкен айырма, млн теңге:", int(diff.max()))
print("  барлық жылда сәйкес келді:", bool((diff == 0).all()))
