"""Решение задания урока 28: отчёт по месяцам и категориям.

Один groupby по двум ключам, свои имена столбцов, доля внутри месяца через
transform — и сортировка, которая делает отчёт читаемым.
"""

import pandas as pd

rows = [
    ("2026-01-03", "Костанай", "еда", 4200),
    ("2026-01-05", "Костанай", "топливо", 18500),
    ("2026-01-07", "Рудный", "еда", 2600),
    ("2026-01-09", "Костанай", "связь", 4990),
    ("2026-01-15", "Костанай", "аренда", 95000),
    ("2026-01-18", "Рудный", "топливо", 16200),
    ("2026-01-24", "Костанай", "еда", 3100),
    ("2026-02-02", "Рудный", "еда", 2800),
    ("2026-02-06", "Костанай", "топливо", 19100),
    ("2026-02-11", "Костанай", "связь", 4990),
    ("2026-02-15", "Костанай", "аренда", 95000),
    ("2026-02-20", "Рудный", "аренда", 62000),
]
df = pd.DataFrame(rows, columns=["day", "city", "kind", "amount"])
df["day"] = pd.to_datetime(df["day"])
df["месяц"] = df["day"].dt.to_period("M")

report = df.groupby(["месяц", "kind"]).agg(
    чеков=("amount", "count"),
    всего=("amount", "sum"),
).reset_index()

# Доля внутри своего месяца, а не от всего периода.
report["доля"] = (report["всего"] / report.groupby("месяц")["всего"].transform("sum") * 100).round(1)
report = report.sort_values(["месяц", "всего"], ascending=[True, False])

print(report.to_string(index=False))

print()
totals = df.groupby("месяц")["amount"].sum()
print("итог по месяцам:", {str(k): int(v) for k, v in totals.items()})
print("месяц с наибольшими расходами:", totals.idxmax())
