"""Решение задания урока 27: три вопроса к одной таблице чеков.

Дорогие чеки одного города, отметка «крупный» через loc и сумма по городам
только по крупным — всё это выборки, а не циклы.
"""

import pandas as pd

rows = [
    ("2026-01-03", "Костанай", "еда", 4200),
    ("2026-01-05", "Костанай", "топливо", 18500),
    ("2026-01-07", "Рудный", "еда", 2600),
    ("2026-01-09", "Костанай", "связь", 4990),
    ("2026-01-12", "Астана", "еда", 7300),
    ("2026-01-15", "Костанай", "аренда", 95000),
    ("2026-01-18", "Рудный", "топливо", 16200),
    ("2026-01-21", "Астана", "связь", 4990),
    ("2026-01-24", "Костанай", "еда", 3100),
    ("2026-01-27", "Рудный", "аренда", 62000),
]
df = pd.DataFrame(rows, columns=["day", "city", "kind", "amount"])
df["day"] = pd.to_datetime(df["day"])

print("дороже 5000 в Костанае:")
mask = (df["city"] == "Костанай") & (df["amount"] > 5000)
print(df.loc[mask, ["day", "amount"]].to_string(index=False))

print()
print("размер чека:")
df["размер"] = "обычный"
df.loc[df["amount"] >= 20000, "размер"] = "крупный"
print(df["размер"].value_counts().to_string())

print()
print("крупные по городам:")
big = df.loc[df["размер"] == "крупный", ["city", "amount"]]
print(big.groupby("city")["amount"].sum().to_string())
